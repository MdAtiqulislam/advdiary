abstract class AppDimensions {
  // Padding
  static const double horizontalPadding = 16.0;   // Default horizontal padding for screens
  static const double verticalPadding = 16.0;     // Default vertical padding for screens
  static const double sectionPadding = 24.0;      // Larger padding for sections
  static const double widgetPadding = 16.0;       // Standard padding inside widgets
  static const double contentPadding = 8.0;       // Small padding for content spacing

  // Text Sizes
  static const double titleTextSize = 20.0;       // For page titles
  static const double headerTextSize = 14.0;      // For headers / subheaders
  static const double bodyTextSize = 12.0;        // Default body text
  static const double smallTextSize = 10.0;       // Small / muted text
  static const double captionTextSize = 8.0;     // Very small text / captions

  // Border radius
  static const double borderRadiusSmall = 4.0;    // For small buttons/cards
  static const double borderRadius = 6.0;         // Default radius for cards/buttons
  static const double borderMedium = 12.0;         // Default radius for cards/buttons
  static const double borderRadiusLarge = 21.0;   // Larger radius for bigger widgets

  // Icon / spacing
  static const double iconSizeSmall = 16.0;
  static const double iconSizeMedium = 24.0;
  static const double iconSizeLarge = 32.0;

  // Elevation
  static const double cardElevation = 2.0;
  static const double buttonElevation = 3.0;
}
